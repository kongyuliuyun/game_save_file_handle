@functools.lru_cache(maxsize=256)
def pixmap(name: str, color: str, size: int = 20) -> QPixmap:
    """渲染指定图标为 ``QPixmap``（带 2x 缩放保证高分屏清晰）。"""
    body = _BODIES.get(name)
    if body is None:
        return QPixmap()

    svg = _SVG_TEMPLATE.format(color=color, body=body)
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    scale = 2
    result = QPixmap(size * scale, size * scale)
    result.fill(Qt.GlobalColor.transparent)
    painter = QPainter(result)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
    renderer.render(painter, QRectF(0, 0, size * scale, size * scale))
    painter.end()
    result.setDevicePixelRatio(scale)
    return result


def icon(name: str, color: str, size: int = 20) -> QIcon:
    """构造 QIcon。"""
    result = QIcon()
    image = pixmap(name, color, size)
    if image.isNull():
        return result
    result.addPixmap(image)
    return result
